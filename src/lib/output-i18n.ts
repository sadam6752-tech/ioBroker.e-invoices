/**
 * Languages of what the adapter hands to its user outside the web app: the CSV and Excel exports (lists, open items,
 * revenue, dunning suggestions) and the dunning letters with their default texts.
 *
 * The invoices themselves (PDF, XML, the Excel copy of an invoice) and the DATEV file stay German: they are German
 * tax documents, and the DATEV format prescribes its German headers.
 *
 * The key of every text is its English wording, so a missing translation falls back to English.
 */

/** The eleven languages of ioBroker. */
export const OUTPUT_LANGUAGES = ['en', 'de', 'ru', 'pt', 'nl', 'fr', 'it', 'es', 'pl', 'uk', 'zh-cn'] as const;

/** One of the eleven languages of ioBroker. */
export type OutputLanguage = (typeof OUTPUT_LANGUAGES)[number];

/** The languages with a translation table (English is the key itself). */
type Translated = Exclude<OutputLanguage, 'en'>;

/**
 * Picks a supported language.
 *
 * @param values - Candidates in order of preference, e.g. the language of the web app, then the system language.
 * @returns The first supported one; English when none is.
 */
export function outputLanguage(...values: unknown[]): OutputLanguage {
	for (const value of values) {
		const text = typeof value === 'string' ? value.trim().toLowerCase() : '';
		if ((OUTPUT_LANGUAGES as readonly string[]).includes(text)) {
			return text as OutputLanguage;
		}
		// `zh`, `zh-CN`, `de-DE` and the like
		const base = text.split(/[-_]/)[0];
		if (base === 'zh') {
			return 'zh-cn';
		}
		if ((OUTPUT_LANGUAGES as readonly string[]).includes(base)) {
			return base as OutputLanguage;
		}
	}
	return 'en';
}

