/**
 * Translates a text of the exports or the dunning letters.
 *
 * @param language - Target language.
 * @param key - English text (also the fallback).
 * @param vars - Values for `{name}` placeholders.
 */
export function tr(language: OutputLanguage, key: string, vars?: Record<string, string | number>): string {
	const text = language === 'en' ? key : (OUTPUT_TEXTS[key]?.[language] ?? key);
	return vars ? text.replace(/\{(\w+)\}/g, (slot, name: string) => (name in vars ? String(vars[name]) : slot)) : text;
}

/** BCP-47 locale of a language, for dates and amounts. */
const LOCALES: Record<OutputLanguage, string> = {
	en: 'en-GB',
	de: 'de-DE',
	ru: 'ru-RU',
	pt: 'pt-PT',
	nl: 'nl-NL',
	fr: 'fr-FR',
	it: 'it-IT',
	es: 'es-ES',
	pl: 'pl-PL',
	uk: 'uk-UA',
	'zh-cn': 'zh-CN',
};

/**
 * Writes an ISO date the way the language does (German: `28.09.2026`).
 *
 * @param iso - `YYYY-MM-DD` (time part ignored).
 * @param language - Target language.
 */
export function formatOutputDate(iso: string, language: OutputLanguage): string {
	const [year, month, day] = iso.slice(0, 10).split('-').map(Number);
	if (!year || !month || !day) {
		return iso;
	}
	if (language === 'de') {
		return `${String(day).padStart(2, '0')}.${String(month).padStart(2, '0')}.${year}`;
	}
	return new Intl.DateTimeFormat(LOCALES[language], {
		year: 'numeric',
		month: '2-digit',
		day: '2-digit',
		timeZone: 'UTC',
	}).format(new Date(Date.UTC(year, month - 1, day)));
}

/**
 * Writes an amount in euro the way the language does (German: `119,00 €`).
 *
 * @param amount - Amount in EUR.
 * @param language - Target language.
 */
export function formatOutputAmount(amount: number, language: OutputLanguage): string {
	if (language === 'de') {
		return `${amount.toFixed(2).replace('.', ',')} €`;
	}
	return new Intl.NumberFormat(LOCALES[language], { style: 'currency', currency: 'EUR' }).format(amount);
}
